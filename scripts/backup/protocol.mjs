export function operatorFailureMessage(cause) {
  return cause instanceof BackupOperatorError?cause.message:'Backup operation failed. Check the private configuration, archive and protected server logs. No credentials or remote response bodies are printed.';
}
const fingerprint = value => sha256(Buffer.from(value));
function encryptionKey(value) {
  if(typeof value!=='string') error('The secrets file is missing STORAGE_ENC_KEY.');
  const decoded=/^[a-f0-9]{64}$/i.test(value)?Buffer.from(value,'hex'):Buffer.from(value,'base64');
  if(decoded.length!==32) error('STORAGE_ENC_KEY must decode to 32 bytes.');
  return decoded;
}
function origin(value, allowLocal=false) {
  const url=new URL(value);
  const local=['localhost','127.0.0.1','[::1]'].includes(url.hostname);
  if(url.username||url.password||url.search||url.hash||url.pathname!=='/'||(url.protocol!=='https:' && !(allowLocal && local && url.protocol==='http:'))) error('Use an HTTPS origin, or explicitly enable isolated localhost testing.');
  return url.origin;
}
async function boundedJson(response) {
  if(!response.ok) {
    let code; const chunks=[];let size=0;
    try {
      for await(const bytes of response.body??[]){size+=bytes.length;if(size>16*1024)break;chunks.push(bytes);}
      if(size<=16*1024){const parsed=JSON.parse(Buffer.concat(chunks).toString('utf8'));if(Object.hasOwn(API_FAILURE_HINTS,parsed?.error))code=parsed.error;}
    }catch{/* Unknown upstream responses remain redacted. */}
    error(code?`${code} (HTTP ${response.status}): ${API_FAILURE_HINTS[code]}`:`Operator API request failed (HTTP ${response.status}). Inspect the maintenance status and protected server logs; preserve the archive and recovery key.`);
  }
  const chunks=[]; let size=0;
  for await(const chunk of response.body??[]) {size+=chunk.length;if(size>MAX_JSON)error('Operator API response exceeds its bound.');chunks.push(chunk);}
  try{return JSON.parse(Buffer.concat(chunks).toString('utf8'));}catch{error('Operator API returned invalid JSON.');}
}
export class OperatorAPI {
  constructor(settings,{fetcher=fetch,allowLocal=false}={}) {
    this.origin=origin(settings.origin,allowLocal);this.secret=settings.bootstrapSecret;this.fetcher=fetcher;this.allowLocal=allowLocal;
    if(typeof this.secret!=='string'||this.secret.length<32)error('A strong operator bootstrap secret is required in the private configuration.');
  }
  async json(path,body) {
    const url=new URL(path,this.origin);
    if(url.origin!==this.origin)error('Operator API path left its configured origin.');
    const encoded=body===undefined?undefined:JSON.stringify(body);
    if(encoded && Buffer.byteLength(encoded)>MAX_JSON)error('Operator API request exceeds its bound.');
    return boundedJson(await this.fetcher(url,{method:body===undefined?'GET':'POST',headers:{'x-bootstrap-secret':this.secret,'content-type':'application/json',accept:'application/json'},body:encoded,redirect:'error',signal:AbortSignal.timeout(60_000)}));
  }
  headersFor(url, supplied={}, operatorAuth=false) {
    const parsed=new URL(url), headers=new Headers(supplied);
    const local=['localhost','127.0.0.1','[::1]'].includes(parsed.hostname);
    if(parsed.username||parsed.password||parsed.hash||(parsed.protocol!=='https:'&&!(this.allowLocal&&local&&parsed.protocol==='http:')))error('Object transfer URL is not allowed.');
    if(headers.has('x-bootstrap-secret')||headers.has('authorization')||headers.has('cookie'))error('Object transfer included unexpected credential headers.');
    if(operatorAuth){if(parsed.origin!==this.origin)error('Refusing to send an operator credential to another origin.');headers.set('x-bootstrap-secret',this.secret);}
    return headers;
  }
  async download(entry) {
    const url=entry.downloadUrl;
    if(typeof url!=='string')error('Object inventory is missing its download URL.');
    const operatorAuth=entry.kind==='audit';
    const response=await this.fetcher(url,{headers:this.headersFor(url,{},operatorAuth),redirect:'error',signal:AbortSignal.timeout(300_000)});
    if(!response.ok||!response.body){await response.body?.cancel().catch(()=>{});error(`Object download failed (HTTP ${response.status}).`);}
    // Node/Undici finalizes an unreachable Response by cancelling an unlocked,
    // unread body. The archive writer first awaits file creation and can lose
    // the Response during that gap, observing an empty stream instead of bytes.
    // Acquire the native iterator's read lock BEFORE returning from this method.
    // Its return() also cancels correctly even before the first next() call.
    return response.body[Symbol.asyncIterator]();
  }
  async upload(ticket,entry,body) {
    const headers=this.headersFor(ticket.url,ticket.headers??{},ticket.requiresOperatorAuth===true||entry.objectKind==='audit');
    headers.set('content-length',String(entry.bytes));
    const response=await this.fetcher(ticket.url,{method:'PUT',headers,body:Readable.from(body),duplex:'half',redirect:'error',signal:AbortSignal.timeout(300_000)});
    await response.body?.cancel();
    if(!response.ok&&response.status!==412)error(`Object restore failed (HTTP ${response.status}).`);
    // 412 is accepted only after the independent server verification call made
    // by restoreArchive. Existing destination bytes are never overwritten.
  }
}
export async function loadConfiguration(path) {
  const config=await privateJson(path);
  for(const name of ['sourceSecretsFile','targetSecretsFile','targetStorageSecretsFile'])if(config[name])config[name]=resolve(dirname(resolve(path)),config[name]);
  return config;
}
const PHASES=new Set(['freezing','exporting','importing','committing','releasing','complete','aborted']);
async function configuredOperator(config,target,fetcher) {
  const path=target?config.targetSecretsFile:config.sourceSecretsFile;
  if(!path)error(`Set ${target?'targetSecretsFile':'sourceSecretsFile'} in the private configuration.`);
  const secrets=await privateJson(path),settings=target?config.target:config.source;
  return new OperatorAPI({...settings,bootstrapSecret:target?secrets.BOOTSTRAP_SECRET:settings?.bootstrapSecret??secrets.BOOTSTRAP_SECRET},{fetcher,allowLocal:config.allowInsecureLocalhost===true});
}
function safeStatus(report,expectedMode) {
  if(report.mode!==expectedMode)error('The server is in the wrong maintenance mode for this command.');
  const value=report.session;
  if(value===null)return {mode:expectedMode,maintenance:true,session:null};
  if(!value||value.mode!==expectedMode||typeof value.backupId!=='string'||!/^[A-Za-z0-9_-]{8,128}$/.test(value.backupId)
    ||!PHASES.has(value.phase)||!Array.isArray(value.organizations)||value.organizations.length>100
    ||!Array.isArray(value.targets)||value.targets.length>512)error('The server returned an invalid maintenance status.');
  return {mode:expectedMode,maintenance:true,session:{id:value.backupId,phase:value.phase,organizationCount:value.organizations.length,
    targetCount:value.targets.length,complete:value.phase==='complete',aborted:value.phase==='aborted'}};
}
export async function operatorStatus(config,{target=false,fetcher=fetch}={}) {
  const api=await configuredOperator(config,target,fetcher),mode=target?'restore':'export';
  return safeStatus(await api.json(`/v1/admin/${target?'restore':'backup'}/status`),mode);
}
export async function abortSourceBackup(config,{fetcher=fetch}={}) {
  const api=await configuredOperator(config,false,fetcher),report=await api.json('/v1/admin/backup/status');
  const status=safeStatus(report,'export');
  if(!report.session)return {...status,alreadyTerminal:true};
  const declared=config.organizations,session=report.session;
  if(!Array.isArray(declared)||!declared.length||declared.some(id=>typeof id!=='string')||new Set(declared).size!==declared.length
    ||session.scope!=='operator-declared-organizations'||session.organizations.some(id=>typeof id!=='string')
    ||JSON.stringify([...declared].sort())!==JSON.stringify([...session.organizations].sort()))error('The active source backup scope differs from this configuration. Use its original organization declaration; nothing was aborted.');
  if(['complete','aborted'].includes(session.phase))return {...status,alreadyTerminal:true};
  if(!['freezing','exporting','releasing'].includes(session.phase))error('This command can abort only a source export. Restore sessions are never cancelled.');
  await api.json(`/v1/admin/backup/${encodeURIComponent(session.backupId)}/abort`,{});
  // Report fresh state rather than inferring an outcome during a release retry.
  return safeStatus(await api.json('/v1/admin/backup/status'),'export');
}
function checkSecrets(secrets,catalog) {
  if(fingerprint(encryptionKey(secrets.STORAGE_ENC_KEY))!==catalog.encryptionKeyFingerprint
      || fingerprint(secrets.AUTH_SIGNING_SECRET??'')!==catalog.signingSecretFingerprint
      || fingerprint(secrets.BOOTSTRAP_SECRET??'')!==catalog.bootstrapSecretFingerprint) error('The source secret file does not match the frozen deployment.');
}
function targetList(catalog) {
  if(catalog.format!==1||!Array.isArray(catalog.targets)||!catalog.targets.length||catalog.targets.length>10_000)error('Unsupported backup catalog.');
  if(!Array.isArray(catalog.organizations)||!catalog.organizations.length)error('Backup catalog is missing its explicit organization scope.');
  for(const target of catalog.targets){if(typeof target.id!=='string'||!target.schema||!Array.isArray(target.schema.tables)||target.schema.tables.length>512)error('Invalid target schema catalog.');}
  return catalog.targets;
}
export async function createBackup(config,{directory,keyPath,fetcher=fetch,concurrency=4,progress=()=>{}}) {
  if(!Array.isArray(config.organizations)||!config.organizations.length||config.organizations.some(id=>typeof id!=='string'||!id))error('Declare all source organizations explicitly in the private configuration.');
  if(!config.sourceSecretsFile)error('Set sourceSecretsFile in the private configuration.');
  if(!Number.isInteger(concurrency)||concurrency<1||concurrency>8)error('Transfer concurrency must be between one and eight.');
  const secrets=await privateJson(config.sourceSecretsFile), api=new OperatorAPI({...config.source,bootstrapSecret:config.source?.bootstrapSecret??secrets.BOOTSTRAP_SECRET},{fetcher,allowLocal:config.allowInsecureLocalhost===true});
  const writer=await ArchiveWriter.create(directory,keyPath); let session;
  try {
    session=await api.json('/v1/admin/backup/start',{organizations:config.organizations,scope:'operator-declared-organizations'});
    const targets=targetList(session);checkSecrets(secrets,session);
    const root=`/v1/admin/backup/${encodeURIComponent(session.backupId)}`;
    await writer.add({kind:'secrets'},[jsonBytes(secrets)]);
    for(const target of targets){
      let pageIndex=0;
      for(const table of target.schema.tables){
        let after=-1, pages=0;
        do {
          const query=new URLSearchParams({target:target.id,table:table.name,afterRowId:String(after)});
          const page=await api.json(`${root}/metadata?${query}`);
          if(page.table!==table.name||!Array.isArray(page.rows)||!Array.isArray(page.columns)
              || sha256(jsonBytes({table:page.table,columns:page.columns,rows:page.rows,nextRowId:page.nextRowId}))!==page.digest)error('Source metadata page failed its digest check.');
          await writer.add({kind:'metadata',targetId:target.id,table:table.name,pageIndex:pageIndex++},[jsonBytes(page)]);
          if(page.nextRowId===null)break;
          if(!Number.isSafeInteger(page.nextRowId)||page.nextRowId<=after||++pages>MAX_ENTRIES)error('Source metadata cursor did not advance.');
          after=page.nextRowId;
        }while(true);
      }
      target.pageCount=pageIndex;target.expectedObjectCount=0;
      if(target.kind==='filespace'){
        let cursor, pages=0;
        do {
          const query=new URLSearchParams({target:target.id});if(cursor)query.set('cursor',cursor);
          const page=await api.json(`${root}/objects?${query}`);
          if(!Array.isArray(page.entries)||page.entries.length>256)error('Invalid bounded object inventory.');
          for(let i=0;i<page.entries.length;i+=concurrency){
            const group=await Promise.allSettled(page.entries.slice(i,i+concurrency).map(async entry=>{
              if(entry.targetId!==target.id||!['data','audit'].includes(entry.kind)||typeof entry.key!=='string')error('Invalid source object descriptor.');
              const canonical=entry.key.slice(entry.key.lastIndexOf('/')+1);
              const expectedSha256=entry.sha256??(entry.kind==='data'&&/^[a-f0-9]{64}$/.test(canonical)?canonical:undefined);
              const body=await api.download(entry);
              await writer.add({kind:'object',targetId:target.id,objectKind:entry.kind,key:entry.key},body,{expectedBytes:entry.bytes,expectedSha256});
              target.expectedObjectCount++;
            }));
            for(const result of group)if(result.status==='rejected')throw result.reason;
          }
          progress({phase:'download',objects:target.expectedObjectCount});
          if(page.nextCursor===null)break;
          if(typeof page.nextCursor!=='string'||!page.nextCursor||page.nextCursor===cursor||++pages>MAX_ENTRIES)error('Source object cursor did not advance.');
          cursor=page.nextCursor;
        }while(true);
      }
    }
    const manifest=await writer.commit({createdAt:new Date().toISOString(),sourceOrigin:api.origin,backupId:session.backupId,apiVersion:session.apiVersion,
      scope:'operator-declared-organizations',organizations:session.organizations,discoveredOrganizations:session.discoveredOrganizations,
      encryptionKeyFingerprint:session.encryptionKeyFingerprint,signingSecretFingerprint:session.signingSecretFingerprint,
      bootstrapSecretFingerprint:session.bootstrapSecretFingerprint,targets});
    await api.json(`${root}/finish`,{});
    return {archiveId:manifest.archiveId,entries:manifest.entryCount,bytes:manifest.totalBytes};
  }catch(cause){
    await writer.abort();
    if(session?.backupId)await api.json(`/v1/admin/backup/${encodeURIComponent(session.backupId)}/abort`,{}).catch(()=>{});
    throw cause;
  }
}
export async function prepareTargetSecrets(config,verified,outputPath,archiveDirectory) {
  outputPath=join(await realpath(dirname(resolve(outputPath))),basename(outputPath));
  if(inside(await realpath(archiveDirectory),outputPath))error('Keep target secrets outside the encrypted archive.');
  const storage=config.targetStorageSecretsFile?await privateJson(config.targetStorageSecretsFile):{};
  for(const key of ['S3_ACCESS_KEY_ID','S3_SECRET_ACCESS_KEY'])if(typeof storage[key]!=='string'||!storage[key])error('Provide fresh target storage credentials in targetStorageSecretsFile.');
  const secrets={...verified.secrets};
  for(const key of Object.keys(secrets))if(key.startsWith('S3_')||['AUTH_SIGNING_SECRET','BOOTSTRAP_SECRET','SIGNUP_INVITE_TOKENS'].includes(key))delete secrets[key];
  Object.assign(secrets,storage,{STORAGE_ENC_KEY:verified.secrets.STORAGE_ENC_KEY,AUTH_SIGNING_SECRET:randomBytes(32).toString('hex'),BOOTSTRAP_SECRET:randomBytes(32).toString('hex')});
  await exclusiveJson(resolve(outputPath),secrets);
  return {prepared:true};
}
export async function restoreArchive(config,{directory,key,fetcher=fetch,concurrency=4,prepareSecrets,progress=()=>{}}) {
  // Absolutely no target request happens before every local member, index, tag,
  // logical page digest, and checksum has passed full verification.
  const verified=await verifyArchive(directory,key), {manifest,secrets}=verified;
  checkSecrets(secrets,manifest);targetList(manifest);
  if(prepareSecrets)return prepareTargetSecrets(config,verified,prepareSecrets,directory);
  if(!config.targetSecretsFile)error('Prepare and deploy fresh target secrets, then set targetSecretsFile.');
  const targetSecrets=await privateJson(config.targetSecretsFile);
  if(fingerprint(encryptionKey(targetSecrets.STORAGE_ENC_KEY))!==manifest.encryptionKeyFingerprint)error('The target must preserve the original storage encryption key.');
  for(const [name,field] of [['AUTH_SIGNING_SECRET','signingSecretFingerprint'],['BOOTSTRAP_SECRET','bootstrapSecretFingerprint']]){
    if(typeof targetSecrets[name]!=='string'||targetSecrets[name].length<32||fingerprint(targetSecrets[name])===manifest[field])error('The target must use fresh authentication and bootstrap secrets.');
  }
  const api=new OperatorAPI({...config.target,bootstrapSecret:targetSecrets.BOOTSTRAP_SECRET},{fetcher,allowLocal:config.allowInsecureLocalhost===true});
  if(api.origin===manifest.sourceOrigin)error('Restore requires a different, fresh maintenance target.');
  if(!Number.isInteger(concurrency)||concurrency<1||concurrency>8)error('Transfer concurrency must be between one and eight.');
  const session=await api.json('/v1/admin/restore/start',{archiveId:manifest.archiveId,scope:manifest.scope,organizations:manifest.organizations,targets:manifest.targets,
    encryptionKeyFingerprint:manifest.encryptionKeyFingerprint,signingSecretFingerprint:manifest.signingSecretFingerprint,bootstrapSecretFingerprint:manifest.bootstrapSecretFingerprint});
  if(typeof session.restoreId!=='string'||!session.restoreId)error('Restore target did not create a maintenance session.');
  const root=`/v1/admin/restore/${encodeURIComponent(session.restoreId)}`;
  const finish=async()=>{
    let revision=-1;
    for(let step=0;step<MAX_ENTRIES;step++){
      const result=await api.json(`${root}/finish`,{targets:manifest.targets.map(target=>({id:target.id,pageCount:target.pageCount}))});
      if(result.complete===true&&result.maintenance===true)return result;
      if(result.complete!==false||result.maintenance!==true||result.phase!=='validating'
          ||!Number.isSafeInteger(result.revision)||result.revision<=revision)error('Restore target did not confirm completed maintenance promotion.');
      revision=result.revision;progress({phase:'validate',step:step+1});
    }
    error('Restore validation exceeded its progress bound; preserve maintenance mode.');
  };
  if(session.phase==='complete')return {archiveId:manifest.archiveId,restoreId:session.restoreId,result:{complete:true,maintenance:true}};
  if(['committing','releasing'].includes(session.phase))return {archiveId:manifest.archiveId,restoreId:session.restoreId,result:await finish()};
  // Register every expected object before uploading any bytes. Per-target
  // bounded pages are replayed identically on restart; server receipts persist.
  let expectations=[], expectationTarget, expectationIndexes=new Map();
  const register=async()=>{
    if(!expectations.length)return;
    const pageIndex=expectationIndexes.get(expectationTarget)??0;
    await api.json(`${root}/objects`,{targetId:expectationTarget,pageIndex,entries:expectations});
    expectationIndexes.set(expectationTarget,pageIndex+1);expectations=[];
  };
  for await(const entry of archiveEntries(directory,key,manifest))if(entry.kind==='object'){
    if(expectationTarget!==entry.targetId){await register();expectationTarget=entry.targetId;}
    expectations.push({kind:entry.objectKind,key:entry.key,sha256:entry.sha256,bytes:entry.bytes});
    if(expectations.length===128)await register();
  }
  await register();
  let group=[], uploaded=0;
  const drain=async()=>{const results=await Promise.allSettled(group);group=[];for(const result of results)if(result.status==='rejected')throw result.reason;};
  try {
    for await(const entry of archiveEntries(directory,key,manifest)){
      if(entry.kind==='metadata'){
        await drain();
        const page=await readJsonMember(directory,key,manifest.archiveId,entry);
        await api.json(`${root}/metadata`,{targetId:entry.targetId,pageIndex:entry.pageIndex,page});
      }else if(entry.kind==='object'){
        group.push((async()=>{
          const identity={targetId:entry.targetId,kind:entry.objectKind,key:entry.key};
          const ticket=await api.json(`${root}/object-url`,identity);
          await api.upload(ticket,entry,decryptedMember(directory,key,manifest.archiveId,entry));
          const receipt=await api.json(`${root}/object-verify`,identity);
          if(receipt.verified!==true)error('Restored object has no verified storage receipt.');
          progress({phase:'restore',objects:++uploaded});
        })());
        if(group.length===concurrency)await drain();
      }
    }
    await drain();
    const result=await finish();
    return {archiveId:manifest.archiveId,restoreId:session.restoreId,objects:uploaded,result};
  }catch(cause){await Promise.allSettled(group);throw cause;} // Leave maintenance staging intact for a safe rerun.
}
