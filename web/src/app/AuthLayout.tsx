/*
 * AuthLayout — the unauthenticated shell: a centered, branded card on the
 * near-black canvas, mirroring the macOS LoginView (brand hero + tagline +
 * "offline" status, then a card via <Outlet/>, then a footnote).
 *
 * Sign-in / sign-up screens render INTO this via the router <Outlet/> and own
 * only their card body + footnote (passed through context-free props they set
 * themselves). Redirects to /filespaces when already authenticated — or to a
 * sanitized `?next=` target (auth-spec W2: /device/authorize bounces signed-out
 * visitors through /signin?next=… and must land back there after the password
 * AND any TOTP/passkey step; the MFA step is in-page, so the URL keeps `next`).
 *
 * FROZEN: screen agents render inside the Outlet; they do not edit this file.
 * (Edited for the auth overhaul per OVERNIGHT/auth-spec.md W2.)
 */
import { useProductName } from './productName'
import { Navigate, Outlet, useLocation } from 'react-router-dom'
import { BrandMark } from '../design'
import { isMockMode } from '../api'
import { sanitizeNext } from './nextParam'
import { useAuth } from './auth'
import './shell.css'

export function AuthLayout() {
  const productName = useProductName()
  const { isAuthenticated, loading } = useAuth()
  const location = useLocation()
  const mock = isMockMode()

  if (loading) {
    return <div className="cfs-auth-layout" aria-busy="true" />
  }
  if (isAuthenticated && !['/reset-password', '/finish-sign-in'].includes(location.pathname)) {
    const next = sanitizeNext(new URLSearchParams(location.search).get('next'))
    return <Navigate to={next ?? '/filespaces'} replace />
  }

  return (
    <main className="cfs-auth-layout">
      <div className="cfs-auth-layout__inner">
        <header className="cfs-hero">
          <BrandMark size={42} chrome className="cfs-hero__plate" />
          <span className="cfs-hero__wordmark">{productName}</span>
          {mock && <span className="cfs-hero__status">Preview · sample data</span>}
        </header>

        {/* sign-in / sign-up screens render their card + footnote here */}
        <Outlet />
      </div>
    </main>
  )
}
